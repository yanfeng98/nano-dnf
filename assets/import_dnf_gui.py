#!/usr/bin/env python3
"""Bake the shop / quest / inventory / dialogue windows out of the DNF client.

The town needs real windows rather than procedure-drawn boxes (`docs/adr/0065`).
Entries are the old-style interface frames 2026-10-24 measured from
`sprite_interface.NPK`; item icons are 28x28 frames from the stackable sheet.
No item-ID -> frame table exists (Script.pvf is encrypted), so the icon frames
below are a small hand-picked set, labelled by what they are used for.

    python3 assets/import_dnf_gui.py --client /home/luyanfeng/dnf-client/地下城与勇士
    python3 assets/import_dnf_gui.py --table
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from import_dnf_scene import decode_at, shelf_pack  # noqa: E402
from import_dnf_ui import cell, decode_run  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_CLIENT = pathlib.Path("/home/luyanfeng/dnf-client/地下城与勇士")
IFACE = "sprite_interface.NPK"
DIGIT = "sprite_interface_digit.NPK"
STACK = "sprite_item_stackable.NPK"
ITEM = "sprite_item.NPK"
OUT = ROOT / "assets" / "gui.png"
META = ROOT / "assets" / "dnf_src" / "gui.json"

# (name, pack, entry, frame, note)
RUNS = [
    ("shop", IFACE, "sprite/interface/stackableshopwindow.img", 0, "消耗品商店窗 291x380"),
    ("quest", IFACE, "sprite/interface/questwindow.img", 19, "任务日志窗 291x380"),
    ("inventory", IFACE, "sprite/interface/iteminventorywindow.img", 0, "背包窗 291x410"),
    ("equipment", IFACE, "sprite/interface/inventorybase.img", 0, "装备/角色底板 291x410"),
    ("dialog", IFACE, "sprite/interface/npc_dialog_ui.img", 0, "NPC 对话窗 618x165"),
    ("gold", DIGIT, "sprite/interface/digit/gold.img", 0, "金币图标 17x21"),
    ("chat", IFACE, "sprite/interface/chatting.img", 0, "旧式聊天窗 317x146"),
]

# (name, pack, entry, frame, note)
ICONS = [
    ("potion0", STACK, "sprite/item/stackable/consumption.img", 0, "消耗品图标候选 0"),
    ("potion1", STACK, "sprite/item/stackable/consumption.img", 1, "消耗品图标候选 1"),
    ("potion2", STACK, "sprite/item/stackable/consumption.img", 2, "消耗品图标候选 2"),
    ("potion3", STACK, "sprite/item/stackable/consumption.img", 3, "消耗品图标候选 3"),
    ("mat0", STACK, "sprite/item/stackable/material.img", 0, "材料图标候选 0"),
    ("mat1", STACK, "sprite/item/stackable/material.img", 1, "材料图标候选 1"),
    ("weapon0", ITEM, "sprite/item/iconweapon.img", 0, "武器图标候选 0"),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--client", type=pathlib.Path, default=DEFAULT_CLIENT)
    ap.add_argument("--preview", action="store_true")
    ap.add_argument("--table", action="store_true")
    args = ap.parse_args()

    art = []
    runs = {}
    for name, pack, entry, first, note in RUNS:
        frames = decode_run(args.client, pack, entry, first, 1)
        run, size, anchor, ink = cell(frames)
        for index, picture in enumerate(run):
            art.append((f"{name}{index}", picture))
        runs[name] = {
            "pack": pack, "entry": entry, "first": first, "frames": len(run),
            "cell": list(size), "anchor": list(anchor), "ink": ink, "note": note,
        }
    icons = {}
    for name, pack, entry, index, note in ICONS:
        picture, offset = decode_at(args.client, pack, entry, index)
        art.append((name, picture))
        icons[name] = {
            "pack": pack, "entry": entry, "frame": index,
            "size": list(picture.size), "offset": list(offset), "note": note,
        }

    width = 1600
    spots, height = shelf_pack([(p.width, p.height) for _, p in art], width)
    sheet = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    rects = {}
    for (name, picture), (x, y, w, h) in zip(art, spots):
        sheet.alpha_composite(picture, (x, y))
        rects[name] = {"x": x, "y": y, "w": w, "h": h}
    for name, block in runs.items():
        block["rects"] = [rects[f"{name}{i}"] for i in range(block["frames"])]
    for name, block in icons.items():
        block["rect"] = rects[name]

    if args.table:
        print("\n    /* generated by assets/import_dnf_gui.py --table - do not hand-edit */")
        for name, block in runs.items():
            r = block["rects"][0]
            print(f'    {name}: {{ cell: [{block["cell"][0]}, {block["cell"][1]}], '
                  f'anchor: [{block["anchor"][0]}, {block["anchor"][1]}], '
                  f'frames: [[{r["x"]}, {r["y"]}, {r["w"]}, {r["h"]}]] }},')
        for name, block in icons.items():
            r = block["rect"]
            print(f'    {name}: {{ rect: [{r["x"]}, {r["y"]}, {r["w"]}, {r["h"]}], '
                  f'size: [{block["size"][0]}, {block["size"][1]}] }},')
        return

    if args.preview:
        target = ROOT / "assets" / "dnf_src" / "gui-preview.png"
        zoom = 2
        out = sheet.resize((sheet.width * zoom, sheet.height * zoom), Image.NEAREST)
        draw = ImageDraw.Draw(out)
        for name, rect in rects.items():
            draw.text((rect["x"] * zoom, rect["y"] * zoom + 2), name, fill=(255, 224, 120))
        out.save(target)
        print(f"preview -> {target} ({out.size[0]}x{out.size[1]})")
        return

    sheet.save(OUT)
    META.parent.mkdir(parents=True, exist_ok=True)
    META.write_text(json.dumps({
        "sheet": {"w": sheet.width, "h": sheet.height},
        "runs": runs, "icons": icons, "rects": rects,
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{len(art)} frames -> {OUT} ({sheet.size[0]}x{sheet.size[1]})")


if __name__ == "__main__":
    main()
